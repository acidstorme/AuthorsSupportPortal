import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { chromium, expect, type Browser } from "@playwright/test";
import { loadProjectEnv } from "../src/server/config/load-env";
import { parseDemoEnv } from "../src/server/config/env-schema";
import { loadSource } from "./lib/source";
import { createSetupClients } from "./lib/adapters";
import { assertMigrations, assertRuntimeAndEmailSafety, assertSignupDisabled } from "./lib/preflight";
loadProjectEnv();
let browser: Browser | undefined;
let clients: ReturnType<typeof createSetupClients> | undefined;
let stage = "configuration";
try {
  const env = parseDemoEnv(process.env, process.argv[2]);
  assert.equal(env.AI_MODE, "mock", "Both app and browser test must use mock mode.");
  assert.ok(["localhost", "127.0.0.1"].includes(new URL(env.APP_URL).hostname), "Run against a local app connected to the approved project.");
  clients = createSetupClients(env); stage = "safety preflight";
  await assertSignupDisabled(env); await assertMigrations(clients.db); await assertRuntimeAndEmailSafety(clients.db, env);
  browser = await chromium.launch({ channel: "msedge", headless: true });
  const authorContext = await browser.newContext({ baseURL: env.APP_URL });
  const adminContext = await browser.newContext({ baseURL: env.APP_URL });
  const otherContext = await browser.newContext({ baseURL: env.APP_URL });
  const [authorRecord, otherRecord] = loadSource().authors;
  const author = await authorContext.newPage();
  const admin = await adminContext.newPage();
  stage = "browser author login";
  await author.goto("/login"); await author.getByLabel("Email address").fill(authorRecord.email); await author.getByLabel("Password", { exact: true }).fill(env.DEMO_AUTHOR_PASSWORD);
  await author.getByRole("button", { name: "Sign in", exact: true }).click(); await expect(author).toHaveURL(/\/author$/);
  await expect(author.getByText(authorRecord.books[0].title, { exact: true }).first()).toBeVisible();
  stage = "browser ticket creation";
  await author.getByRole("link", { name: "Create a ticket" }).click();
  const subject = `[Milestone 6 browser verification] ${randomUUID()}`;
  await author.getByLabel("Subject", { exact: true }).fill(subject); await author.getByLabel("Describe your issue").fill("Synthetic end-to-end review; no support action required.");
  await author.getByLabel("Related book").selectOption(authorRecord.books[0].book_id);
  await author.getByRole("button", { name: "Create ticket", exact: true }).click();
  await expect(author).toHaveURL(/\/author\/tickets\/[0-9a-f-]+$/, { timeout: 20000 });
  const ticketId = new URL(author.url()).pathname.split("/").at(-1)!;
  console.log("Created labelled browser fixture:", ticketId);
  stage = "second-author isolation";
  assert.equal((await otherContext.request.post("/api/auth/login", { headers: { Origin: env.APP_URL }, data: { email: otherRecord.email, password: env.DEMO_AUTHOR_PASSWORD } })).status(), 200);
  assert.equal((await otherContext.request.get(`/api/tickets/${ticketId}`)).status(), 404);
  stage = "browser admin queue/date filters";
  await admin.goto("/login"); await admin.getByLabel("Email address").fill(env.DEMO_ADMIN1_EMAIL); await admin.getByLabel("Password", { exact: true }).fill(env.DEMO_ADMIN_PASSWORD);
  await admin.getByRole("button", { name: "Sign in", exact: true }).click(); await expect(admin).toHaveURL(/\/admin$/);
  stage = "admin queue search";
  await admin.getByLabel("Search subject or author").fill(subject); await admin.getByRole("button", { name: "Search", exact: true }).click();
  const today = (await (await authorContext.request.get(`/api/tickets/${ticketId}`)).json()).data.createdAt.slice(0, 10);
  stage = "admin queue UTC controls";
  await admin.getByLabel("Created from (UTC)").fill(today); await admin.getByLabel("Created through (UTC)").fill(today);
  await admin.getByRole("button", { name: "Oldest unresolved first", exact: true }).click();
  await expect(admin.getByRole("combobox", { name: "sort", exact: true })).toHaveValue("created_asc");
  await expect(admin.getByRole("combobox", { name: "unresolved", exact: true })).toHaveValue("only");
  stage = "admin ticket draft loading";
  await admin.getByRole("link", { name: subject, exact: true }).click();
  await expect(admin.getByText("MOCK · deterministic test draft, not real AI", { exact: false })).toBeVisible({ timeout: 15000 });
  stage = "browser admin notes and public send";
  await admin.getByRole("button", { name: "Take ownership", exact: true }).click();
  await expect(admin.getByRole("button", { name: "Assign to me", exact: true })).toBeDisabled();
  const privateText = `Private browser note ${randomUUID()}`;
  await admin.getByLabel("New private admin note").fill(privateText); await admin.getByRole("button", { name: "Add private note", exact: true }).click();
  await expect(admin.getByText(privateText, { exact: true })).toBeVisible();
  const reply = `Reviewed public browser reply ${randomUUID()}`;
  await admin.getByRole("textbox", { name: "Reviewed public response" }).fill(reply); await admin.getByRole("button", { name: "Send reviewed response", exact: true }).click();
  await expect(admin.getByRole("status", { name: "" }).filter({ hasText: "Response sent" })).toBeVisible();
  stage = "browser-observed author polling";
  // Keep the author's tab active: polling deliberately pauses on hidden tabs.
  await author.bringToFront(); await expect(author.getByText(reply, { exact: true })).toBeVisible({ timeout: 15000 });
  await expect(author.getByText(privateText, { exact: true })).toHaveCount(0);
  assert.equal((await authorContext.request.get(`/api/tickets/${ticketId}/notes`)).status(), 403);
  stage = "resolved replies and admin attention polling";
  await admin.bringToFront(); await admin.getByRole("combobox", { name: "Status", exact: true }).selectOption("RESOLVED"); await admin.getByRole("button", { name: "Apply status", exact: true }).click();
  await expect(admin.getByRole("combobox", { name: "Status", exact: true })).toHaveValue("RESOLVED");
  await author.bringToFront(); await expect(author.getByText("You can reply to this resolved ticket.", { exact: false })).toBeVisible({ timeout: 15000 });
  await author.getByLabel("Your reply", { exact: true }).fill("Author reply after resolution in browser verification"); await author.getByRole("button", { name: "Send reply", exact: true }).click();
  await expect(author.getByLabel("Your reply", { exact: true })).toHaveValue("");
  await admin.bringToFront(); await expect(admin.getByText("A new author reply arrived after resolution.", { exact: false })).toBeVisible({ timeout: 15000 });
  await expect(admin.getByRole("combobox", { name: "Status", exact: true })).toHaveValue("RESOLVED");
  stage = "closed read-only browser state";
  await admin.getByRole("combobox", { name: "Status", exact: true }).selectOption("CLOSED"); await admin.getByRole("button", { name: "Apply status", exact: true }).click();
  await author.bringToFront(); await expect(author.getByText("This ticket is closed.", { exact: false })).toBeVisible({ timeout: 15000 });
  await expect(author.getByLabel("Your reply", { exact: true })).toHaveCount(0);
  console.log("PASS: actual Edge author/admin login, own-book ticket creation, date/oldest queue controls, assignment, private note isolation, reviewed sending, active-tab polling, resolved reply/attention and closed read-only UI. No intercepted APIs or paid AI calls; fixture/history retained.");
} catch {
  console.error(`Portal browser verification stopped during ${stage}. Check local app, approved setup, CA, mock mode and Edge. No secrets printed.`); process.exitCode = 1;
} finally { await browser?.close(); await clients?.db.$disconnect(); }
